"""Упражнение Б — тест(ы) на фикстуру scope="module". См. TASK.md, часть Б.

Нужно минимум ДВА теста в этом файле, иначе scope="module" нечего доказывать
(общий объект виден только когда есть кому его переиспользовать).

Сложности, с которыми столкнулся (заметки ученика/коуча):
- Фикстура Б только создаёт и отдаёт ApiClient; .get() — в тестах, не в фикстуре.
- setup2 в параметре уже объект, не функция → нельзя setup2().
- return vs yield: уборки нет → хватит return; yield нужен когда есть teardown после.
- path обязан начинаться с "/" иначе URL станет ...composts/1 → зависание сокета/DNS.
- calls растёт на одном и том же клиенте: после 1-го get → 1, после 2-го теста → 2
  (если было бы 1 снова — клиент пересоздался, module-scope не сработал).
"""


def test_b_0(setup2):
    client = setup2
    client.get(path="/posts/1")
    assert client.calls == 1


def test_b_1(setup2):
    client = setup2
    client.get(path="/posts/1")
    assert client.calls == 2
